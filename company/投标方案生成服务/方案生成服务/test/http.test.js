const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os'),http=require('node:http'),crypto=require('node:crypto');
test('HTTP login, fixed amount, unpaid download protection, owner isolation and disabled payments',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'gh-http-'));
 process.env.PROPOSAL_DATA_DIR=dir;process.env.PORTAL_ACCOUNTS_FILE=path.join(dir,'accounts.json');
 const token='isolated-test-token',hash=crypto.createHash('sha256').update(token).digest('hex');
 fs.writeFileSync(process.env.PORTAL_ACCOUNTS_FILE,JSON.stringify({sessions:{[hash]:{email:'test@example.invalid',expires:Date.now()+60000}}}));
 const {handler,store}=require('../server');const server=http.createServer(handler);await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));fs.rmSync(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port;
 const headers={'x-forwarded-proto':'https',cookie:'gh_session='+token};
 assert.equal((await fetch(base+'/orders')).status,426);
 assert.equal((await fetch(base+'/orders',{headers:{'x-forwarded-proto':'https'}})).status,401);
 assert.equal((await fetch(base+'/orders',{headers:{...headers,origin:'https://evil.invalid'}})).status,403);
 assert.equal((await fetch(base+'/orders',{method:'POST',headers,body:'{}'})).status,503);
 const profile={company:'测试企业',industry:'制造',products:'',locations:'',erp:'',mode:'',needs:'需要建立进出口流程及库存台账',timeline:''};
 const order=store.create('test@example.invalid',profile,'http_request_12345');
 assert.equal((await fetch(base+'/orders/'+order.id+'/pdf',{headers})).status,409);
 const other=store.create('other@example.invalid',profile,'other_request_12345');
 assert.equal((await fetch(base+'/orders/'+other.id,{headers})).status,404);
 const list=await (await fetch(base+'/orders',{headers})).json();assert.equal(list.orders.length,1);assert.equal(list.orders[0].amountFen,9900);
 assert.equal((await fetch(base+'/orders/'+order.id+'/retry',{method:'POST',headers})).status,409);
});
